import AppKit
import Carbon.HIToolbox

/// Pastes text into whatever field has focus, then puts the old clipboard back.
///
/// The clipboard holds a *promise* rather than the text itself. The target app's read is what
/// fulfils it, so the old clipboard is restored only after the paste has really happened.
/// Restoring on a timer instead is the most common bug in dictation apps: a slow app ends up
/// pasting the old clipboard.
///
/// The read is also the only sign the paste landed. If nothing reads the text soon after ⌘V
/// (no text field focused, or the keystroke got lost), the text stays on the clipboard for real
/// so Sean can press ⌘V himself, and the caller hears it didn't land (Sean, 2026-10-22: it
/// said "Pasted" when it hadn't).
@MainActor
final class Paster: NSObject, NSPasteboardItemDataProvider {
    /// How long the focused app gets to read the text before Speech Key calls the paste missed.
    static let confirmWithin: TimeInterval = 1.0

    enum Result {
        /// The focused app read the text.
        case landed
        /// Nothing read it in time; it's on the clipboard for real.
        case missed
        /// A newer paste started before anything read this one.
        case cutShort
    }

    private var pendingText: String?
    private var savedItems: [[NSPasteboard.PasteboardType: Data]] = []
    private var ourChangeCount = 0
    private var deadline: DispatchWorkItem?
    private var onResult: ((Result) -> Void)?
    /// Tests: leave the keyboard alone and let the test read the clipboard instead.
    var postsKeystroke = true

    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// `done` hears whether the focused app read the text within `confirmWithin`.
    func paste(_ text: String, done: @escaping (Result) -> Void = { _ in }) {
        let pb = NSPasteboard.general
        restoreNow()   // finish any earlier paste first
        savedItems = pb.pasteboardItems?.map { item in
            var dict: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types { if let d = item.data(forType: type) { dict[type] = d } }
            return dict
        } ?? []

        pendingText = text
        let item = NSPasteboardItem()
        item.setDataProvider(self, forTypes: [.string])
        // Clipboard managers that follow nspasteboard.org skip transient items.
        item.setData(Data(), forType: Self.transient)
        item.setData(Data(), forType: Self.autoGenerated)
        pb.clearContents()
        pb.writeObjects([item])
        ourChangeCount = pb.changeCount
        onResult = done

        if postsKeystroke { postCommandV() }

        let work = DispatchWorkItem { [weak self] in self?.missed() }
        deadline = work
        DispatchQueue.main.asyncAfter(deadline: .now() + Self.confirmWithin, execute: work)
    }

    /// Copies text to the clipboard for real (the "Copy Again" menu item).
    func copy(_ text: String) {
        restoreNow()
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
    }

    nonisolated func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        MainActor.assumeIsolated {
            guard let text = pendingText else { return }
            item.setString(text, forType: .string)
            deadline?.cancel()
            deadline = nil
            report(.landed)
            // Give the app a moment to finish reading, then put the old clipboard back.
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.4) { [weak self] in self?.restoreNow() }
        }
    }

    nonisolated func pasteboardFinishedWithDataProvider(_ pasteboard: NSPasteboard) {}

    /// Nothing read the text in time: keep it on the clipboard for real instead of the promise.
    private func missed() {
        deadline = nil
        guard let text = pendingText else { return }
        pendingText = nil
        savedItems = []
        let pb = NSPasteboard.general
        if pb.changeCount == ourChangeCount {
            pb.clearContents()
            pb.setString(text, forType: .string)
        }
        report(.missed)
    }

    private func report(_ result: Result) {
        let done = onResult
        onResult = nil
        done?(result)
    }

    private func restoreNow() {
        deadline?.cancel()
        deadline = nil
        report(.cutShort)
        guard pendingText != nil else { return }
        pendingText = nil
        let pb = NSPasteboard.general
        // Someone else copied something since: leave their clipboard alone.
        guard pb.changeCount == ourChangeCount else { savedItems = []; return }
        pb.clearContents()
        let items: [NSPasteboardItem] = savedItems.map { dict in
            let item = NSPasteboardItem()
            for (type, data) in dict { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pb.writeObjects(items) }
        savedItems = []
    }

    private func postCommandV() {
        let source = CGEventSource(stateID: .privateState)
        let v = Self.keyCode(for: "v") ?? CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = []   // a lingering Command flag can leave Cmd "stuck" in some apps
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    /// The key that types `character` in the current keyboard layout (V isn't key 9 on Dvorak).
    static func keyCode(for character: Character) -> CGKeyCode? {
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let ptr = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else { return nil }
        let data = Unmanaged<CFData>.fromOpaque(ptr).takeUnretainedValue() as Data
        return data.withUnsafeBytes { raw -> CGKeyCode? in
            guard let layout = raw.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return nil }
            for code in 0..<CGKeyCode(128) {
                var deadKeys: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(layout, code, UInt16(kUCKeyActionDown), 0, UInt32(LMGetKbdType()),
                                            OptionBits(kUCKeyTranslateNoDeadKeysBit), &deadKeys, 4, &length, &chars)
                if status == noErr, length == 1, Character(UnicodeScalar(chars[0])!) == character { return code }
            }
            return nil
        }
    }
}
